"""Build the pre-fractured chunk sets for every board building module (plan 126 stage A, document/160).

The Paris modules come from Tools/paris/haussmann.py as seeded Python geometry, so the same code path rebuilds exactly
the mesh the game ships. For each module this splits the geometry into K spatial chunks and writes one Nanite static
mesh per chunk:

  * every triangle lands in exactly one chunk (triangle partition, not a boolean cut), so the chunks reassemble the
    module with no gaps, no overlaps and no new interior faces - the triangle count stays the module's own;
  * each chunk mesh is re-centred on its own centroid, the manifest keeps the offset so the runtime can place it back
    at the building transform and tumble it around its own centre;
  * material slots are the module's own (Tools/paris/haussmann.py SLOT_MATERIALS), so chunks look like the building.

    python Tools/ue_run.py Tools/destruction/build_chunk_meshes.py                # every board module
    python Tools/ue_run.py Tools/destruction/build_chunk_meshes.py --module SM_Hsm_L_02
    python Tools/ue_run.py Tools/destruction/build_chunk_meshes.py --list         # what would be built

Output: /Game/Tread/Destruction/Chunks/SM_<module>_C<i>
Manifest: Saved/Reports/Destruction_Chunks.json and Content/Tread/Destruction/DestructionChunks.json (the runtime reads
the Content copy through FPaths::ProjectContentDir; a cooked build needs a DataAsset instead - see document/160 section 6).
"""
import importlib
import json
import os
import sys

import unreal

HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT = os.path.dirname(os.path.dirname(HERE))
PARIS = os.path.join(PROJECT, "Tools", "paris")
sys.path.insert(0, PARIS)

import geom  # noqa: E402
import paris_common as pc  # noqa: E402
import ue_mesh  # noqa: E402

MODULES = importlib.import_module("04_haussmann_modules")  # same module table / builders as the game assets
OUT_DIR = "/Game/Tread/Destruction/Chunks"
REPORT = os.path.join(pc.REPORT_DIR, "Destruction_Chunks.json")
CONTENT_MANIFEST = os.path.join(PROJECT, "Content", "Tread", "Destruction", "DestructionChunks.json")
# Every module the board's two ISM actors place, i.e. what the middle 4x8 cells are built from.
BOARD_MODULES = ["SM_Hsm_L_%02d" % i for i in range(8)] + ["SM_Hsm_LBurnt_%02d" % i for i in range(3)] + \
                ["SM_Hsm_Infill_%02d" % i for i in range(5)] + ["SM_Hsm_InfillBurnt_00"]
# Library blocks (SM_M3_*) are imported FBX meshes, not generated by haussmann.py: they get rubble, not chunks.
RUBBLE_MESHES = ["/Game/Tread/City/Paris/Meshes/Haussmann/SM_Hsm_LRuin_00",
                 "/Game/Tread/City/Paris/Meshes/Haussmann/SM_Hsm_LRuin_01",
                 "/Game/Tread/City/Paris/Meshes/Haussmann/SM_Hsm_InfillRuin_00",
                 "/Game/Tread/City/Paris/Meshes/Haussmann/SM_Hsm_InfillRuin_01"]


def module_builder(name):
    kind, seed, damage = MODULES.MODULES[name]
    if kind == "l":
        return MODULES.hm.l_piece(seed, damage)
    if kind == "infill":
        return MODULES.hm.infill_piece(seed, damage)
    raise RuntimeError("module %s has kind %s; only l / infill are supported" % (name, kind))


def bounds(mb):
    lo = [1e30, 1e30, 1e30]
    hi = [-1e30, -1e30, -1e30]
    for slot in mb.used_slots():
        for p in mb.data[slot]["p"]:
            for axis in range(3):
                lo[axis] = min(lo[axis], p[axis])
                hi[axis] = max(hi[axis], p[axis])
    return lo, hi


def split(mb, grid):
    """Partition every triangle of `mb` into one of grid[0]*grid[1]*grid[2] cells by its centroid."""
    lo, hi = bounds(mb)
    size = [max(hi[i] - lo[i], 1e-3) for i in range(3)]
    chunks = {}

    def cell_of(centroid):
        cx = min(int((centroid[0] - lo[0]) / size[0] * grid[0]), grid[0] - 1)
        cy = min(int((centroid[1] - lo[1]) / size[1] * grid[1]), grid[1] - 1)
        cz = min(int((centroid[2] - lo[2]) / size[2] * grid[2]), grid[2] - 1)
        return cx, cy, cz

    for slot in mb.used_slots():
        d = mb.data[slot]
        for tri in d["t"]:
            centroid = [sum(d["p"][i][axis] for i in tri) / 3.0 for axis in range(3)]
            key = cell_of(centroid)
            chunk = chunks.setdefault(key, geom.MeshBuilder(mb.slots))
            out = chunk.data[slot]
            base = len(out["p"])
            for i in tri:
                out["p"].append(d["p"][i])
                out["n"].append(d["n"][i])
                out["uv"].append(d["uv"][i])
                out["c"].append(d["c"][i])
            out["t"].append((base, base + 1, base + 2))
    return chunks


def recentre(mb):
    """Move the mesh to its own centroid; returns the offset that puts it back (metres)."""
    used = mb.used_slots()
    if not used:
        return (0.0, 0.0, 0.0)
    lo, hi = bounds(mb)
    centre = [(lo[i] + hi[i]) * 0.5 for i in range(3)]
    for slot in used:
        d = mb.data[slot]
        d["p"] = [(p[0] - centre[0], p[1] - centre[1], p[2] - centre[2]) for p in d["p"]]
    return tuple(centre)


def build_set(name, grid, materials, collision=True, rebuild=False):
    mb = module_builder(name)
    chunks = split(mb, grid)
    records = []
    total = 0
    for index, key in enumerate(sorted(chunks)):
        chunk = chunks[key]
        if not chunk.used_slots():
            continue
        offset = recentre(chunk)
        path = "%s/SM_%s_C%02d" % (OUT_DIR, name.replace("SM_", ""), index)
        if rebuild and unreal.EditorAssetLibrary.does_asset_exist(path):
            # Collision is only applied when the asset is created, so a re-run has to drop and rebuild it.
            unreal.EditorAssetLibrary.delete_asset(path)
        ue_mesh.build_static_mesh(path, chunk, materials, nanite=True, collision=collision)
        tris = sum(len(chunk.data[s]["t"]) for s in chunk.used_slots())
        total += tris
        records.append({"asset": path, "offset_m": [round(v, 3) for v in offset], "triangles": tris})
    source = sum(len(mb.data[s]["t"]) for s in mb.used_slots())
    print("SET %-20s chunks=%d tris=%d/%d" % (name, len(records), total, source))
    return {"module": name, "chunks": records, "chunk_triangles": total, "source_triangles": source}


def main():
    argv = sys.argv[1:]
    # A commandlet (-run=pythonscript) does not always forward trailing arguments, so the same options can come from
    # the environment: TREAD_CHUNK_GRID=3x3x2 TREAD_CHUNK_REBUILD=1.
    grid = (2, 2, 2)
    if os.environ.get("TREAD_CHUNK_GRID"):
        grid = tuple(int(v) for v in os.environ["TREAD_CHUNK_GRID"].lower().split("x"))
    if "--grid" in argv:
        grid = tuple(int(v) for v in argv[argv.index("--grid") + 1].lower().split("x"))
    # Collision is only authored when the asset is created, and the destruction manager spawns the chunks as rigid
    # bodies, so both are on by default; --rebuild drops the old assets first (document/162).
    collision = "--no-collision" not in argv
    rebuild = "--rebuild" in argv or os.environ.get("TREAD_CHUNK_REBUILD") == "1"
    names = BOARD_MODULES
    if os.environ.get("TREAD_CHUNK_MODULE"):
        names = [os.environ["TREAD_CHUNK_MODULE"]]
    if "--module" in argv:
        names = [argv[argv.index("--module") + 1]]
    if "--list" in argv:
        print("MODULES " + json.dumps(names))
        return

    materials = MODULES.slot_materials()
    sets = []
    for name in names:
        try:
            sets.append(build_set(name, grid, materials, collision, rebuild))
        except Exception as error:  # noqa: BLE001 - one bad module must not lose the rest
            print("SET %s FAILED: %s" % (name, error))

    doc = {"schema": "Tread.Destruction.Chunks.v2", "grid": list(grid), "chunks_dir": OUT_DIR, "collision": collision,
           "sets": sets, "rubble_meshes": RUBBLE_MESHES,
           "note": "chunk offset_m is the centroid the chunk mesh was re-centred on; the runtime places chunk i at "
                   "BuildingTransform * Translate(offset_m). Modules without a set fall back to rubble_meshes."}
    for path in (REPORT, CONTENT_MANIFEST):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as handle:
            json.dump(doc, handle, ensure_ascii=False, indent=1)
    print("MANIFEST sets=%d chunks=%d" % (len(sets), sum(len(s["chunks"]) for s in sets)))
    print("REPORT", REPORT)
    print("CONTENT", CONTENT_MANIFEST)


main()
